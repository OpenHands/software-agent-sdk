#!/usr/bin/env python3
"""Generate the vendored Agent Threat Rules (ATR) injection pattern set.

Reads ATR rules at a pinned release tag from a local git checkout (through
``git archive``; the checkout's working tree is not touched) and writes the
data module ``defense_in_depth/_atr_pattern_data.py`` plus
``.pr/atr_patterns_report.json`` (the repo's PR-only directory, so each refresh
PR carries its own report), which lists every candidate left out and every
dropped condition with the reason.

Selection: ATR's enforce lane (``maturity: stable``, ``status`` not draft or
deprecated, no embedding confirmation, plain OR-ed regex conditions), an
injection category, and tagged both OWASP LLM01:2025 and ASI01:2026.

Each condition on a text field must convert under ``atr_regex_checks``,
stay within the ReDoS budget, and, after ``_normalize`` (the analyzer's own
view), match none of the rule's true_negatives and no benign corpus text.
A rule is vendored only if its surviving conditions still match every one
of its text-field true_positives.

Usage::

    uv run python scripts/generate_atr_patterns.py \\
        --atr-repo ../agent-threat-rules --ref v4.1.5
"""

from __future__ import annotations

import argparse
import io
import json
import re
import subprocess
import sys
import sysconfig
import tarfile
import tempfile
import textwrap
from collections.abc import Iterable, Iterator
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml
from atr_regex_checks import (
    REDOS_INPUT_CHARS,
    REDOS_NATIVE_FACTOR,
    WORKERS,
    convert,
    time_patterns,
)

from openhands.sdk.security.defense_in_depth.utils import _normalize


ATR_URL = "https://github.com/Agent-Threat-Rule/agent-threat-rules"
REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_MODULE = (
    REPO_ROOT
    / "openhands-sdk/openhands/sdk/security/defense_in_depth/_atr_pattern_data.py"
)
OUT_REPORT = REPO_ROOT / ".pr/atr_patterns_report.json"

INJECTION_CATEGORIES = (
    "prompt-injection",
    "tool-poisoning",
    "context-exfiltration",
    "excessive-autonomy",
    "agent-manipulation",
)
REQUIRED_OWASP_LLM = "LLM01:2025"
REQUIRED_OWASP_AGENTIC = "ASI01:2026"
TEXT_FIELDS = ("user_input", "content")
TP_KEYS = ("input", "user_input", "content")
TN_KEYS = (
    "input",
    "user_input",
    "content",
    "agent_output",
    "tool_response",
    "tool_args",
    "tool_description",
    "tool_call",
)
# Only ``critical`` reaches HIGH. ATR's verdict denies critical matches
# unconditionally, denies high only at confidence >= 0.8 (otherwise it asks)
# and never denies medium (it asks at >= 0.6); a bare regex has no confidence.
SEVERITY_BUCKET = {"critical": "high", "high": "medium", "medium": "medium"}
# Benchmark scaffolding, not attack text: a task-template key, the HackAPrompt
# canary phrase (plain, spaced and zero-width forms) and placeholder attacker
# domains. Real attacks do not carry them, so a condition whose ATR source
# contains one is dropped; the rule then has to pass the true-positive check
# without it.
SCAFFOLDING_MARKERS = {
    "attacker_objective": "benchmark task-template key",
    "PWNED": "HackAPrompt canary phrase",
    "P\\s+W\\s+N\\s+E\\s+D": "HackAPrompt canary phrase (spaced)",
    "P[\\u200B": "HackAPrompt canary phrase (zero-width)",
    "ammyscam": "placeholder scam domains from a benchmark task",
    "(?:attacker|evil|exfil": "placeholder attacker hostnames",
}

# ATR's own benign data at the pinned ref, including the hand-written per-rule
# near-miss samples (``*benign-twins*``).
ATR_BENIGN_PREFIXES = (
    "data/benign-corpus-extended",
    "data/benign-code",
    "data/skill-benchmark/benign",
    "data/fn-mine-benign",
)
SDK_BENIGN_GLOBS = (
    "*.md",
    "openhands-sdk/**/*.py",
    "openhands-sdk/**/*.j2",
    "openhands-sdk/**/*.md",
    "openhands-tools/**/*.py",
    "openhands-tools/**/*.j2",
    "openhands-tools/**/*.md",
)
# Text that legitimately contains attack strings: the analyzers themselves.
SDK_BENIGN_SKIP = ("/security/",)
PYTHON_SKIP = ("/test/", "/tests/", "/site-packages/", "/__pycache__/")
BENIGN_WINDOW = 30_000
BENIGN_OVERLAP = 1_000


MODULE_TEMPLATE = '''\
"""Generated data for ``atr_patterns``; see that module for how to use it."""

# Agent Threat Rules {ref}, commit {commit}
# {url}
# SPDX-License-Identifier: MIT
#
{license}
#
# Generated by scripts/generate_atr_patterns.py. Do not edit by hand.

ATR_RELEASE = "{ref}"

ATR_INJECTION_HIGH_PATTERNS: tuple[tuple[str, str, str], ...] = (
{high}
)

ATR_INJECTION_MEDIUM_PATTERNS: tuple[tuple[str, str, str], ...] = (
{medium}
)
'''


@dataclass
class Condition:
    index: int
    source: str
    pattern: str | None = None
    dropped: str | None = None


@dataclass
class Rule:
    rule_id: str
    title: str
    bucket: str
    conditions: list[Condition]
    true_positives: list[str]
    true_negatives: list[str]
    excluded: list[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------


def _git(repo: Path, *args: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True
    ).stdout


def load_tree(repo: Path, ref: str) -> tuple[str, dict[str, bytes]]:
    """Resolve ``ref`` and read rules plus benign data at that commit."""
    commit = _git(repo, "rev-parse", "--verify", f"{ref}^{{commit}}").decode().strip()
    archive = _git(
        repo,
        "archive",
        "--format=tar",
        commit,
        "rules",
        "LICENSE",
        *ATR_BENIGN_PREFIXES,
    )
    files: dict[str, bytes] = {}
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        for member in tar.getmembers():
            handle = tar.extractfile(member) if member.isfile() else None
            if handle is not None:
                files[member.name] = handle.read()
    return commit, files


def _mit_license(files: dict[str, bytes]) -> str:
    """ATR's LICENSE at the pinned commit; stop if it is no longer MIT."""
    text = files.get("LICENSE", b"").decode("utf-8")
    if not text.startswith("MIT License"):
        raise SystemExit(
            "ATR's LICENSE at this ref is not MIT; check before vendoring."
        )
    return text


def _texts(case: dict[str, Any], keys: Iterable[str]) -> list[str]:
    values = (case.get(key) for key in keys)
    return [
        value if isinstance(value, str) else json.dumps(value)
        for value in values
        if value
    ]


def _case_texts(cases: list[Any] | None, keys: Iterable[str]) -> list[str]:
    keys = tuple(keys)
    return [
        text
        for case in cases or []
        for text in (_texts(case, keys) if isinstance(case, dict) else [str(case)])
    ]


def _in_scope(raw: dict[str, Any], category: str) -> str | None:
    """Why an enforce-lane rule is out of the injection scope, if it is."""
    references = raw.get("references") or {}
    llm = " ".join(references.get("owasp_llm") or [])
    agentic = " ".join(references.get("owasp_agentic") or [])
    if category not in INJECTION_CATEGORIES:
        return f"category {category} is not an injection category"
    if REQUIRED_OWASP_LLM not in llm or REQUIRED_OWASP_AGENTIC not in agentic:
        return f"not tagged both {REQUIRED_OWASP_LLM} and {REQUIRED_OWASP_AGENTIC}"
    return None


def _lane_gap(raw: dict[str, Any]) -> str | None:
    """Why an enforce-lane rule cannot be expressed as independent regexes."""
    detection = raw.get("detection") or {}
    if str(raw.get("confirm") or "") == "embedding":
        return "fires in the enforce lane only after embedding confirmation"
    tier = str(raw.get("detection_tier") or detection.get("method") or "pattern")
    if tier != "pattern":
        return f"detection tier {tier} is not a plain pattern"
    if str(detection.get("condition")) != "any":
        return "conditions are not combined with any (OR)"
    return None


def _condition(index: int, raw: dict[str, Any]) -> Condition:
    source = str(raw.get("value", ""))
    if raw.get("operator") != "regex" or raw.get("field") not in TEXT_FIELDS:
        reason = f"{raw.get('operator')} on field {raw.get('field')} is not text regex"
        return Condition(index=index, source=source, dropped=reason)
    marker = next((m for m in SCAFFOLDING_MARKERS if m in source), None)
    if marker is not None:
        reason = (
            f"benchmark scaffolding, not attack text: {SCAFFOLDING_MARKERS[marker]}"
        )
        return Condition(index=index, source=source, dropped=reason)
    if raw.get("case_sensitive"):
        reason = "case-sensitive in ATR; the analyzer compiles with IGNORECASE"
        return Condition(index=index, source=source, dropped=reason)
    return Condition(index=index, source=source)


def select_rules(files: dict[str, bytes]) -> tuple[list[Rule], dict[str, str]]:
    """Enforce-lane injection rules, plus why other enforce-lane rules are out."""
    rules: list[Rule] = []
    out_of_scope: dict[str, str] = {}
    for path in sorted(p for p in files if p.startswith("rules/")):
        if not path.endswith(".yaml"):
            continue
        raw = yaml.safe_load(files[path])
        maturity = str(raw.get("maturity") or "").strip()
        if raw.get("status") in ("draft", "deprecated") or maturity != "stable":
            continue
        bucket = SEVERITY_BUCKET.get(str(raw.get("severity")))
        reason = (
            _in_scope(raw, path.split("/")[1])
            or _lane_gap(raw)
            or (None if bucket else f"severity {raw.get('severity')} is unmapped")
        )
        if reason is not None or bucket is None:
            out_of_scope[raw["id"]] = reason or "unmapped"
            continue
        cases = raw.get("test_cases") or {}
        rules.append(
            Rule(
                rule_id=raw["id"],
                title=" ".join(str(raw["title"]).split()),
                bucket=bucket,
                conditions=[
                    _condition(i, c)
                    for i, c in enumerate(raw["detection"]["conditions"])
                ],
                true_positives=_case_texts(cases.get("true_positives"), TP_KEYS),
                true_negatives=_case_texts(cases.get("true_negatives"), TN_KEYS),
            )
        )
    return rules, out_of_scope


# ---------------------------------------------------------------------------
# Benign corpora
# ---------------------------------------------------------------------------


def _windows(text: str) -> Iterator[str]:
    normalized = _normalize(text)
    step = BENIGN_WINDOW - BENIGN_OVERLAP
    for start in range(0, max(1, len(normalized)), step):
        yield normalized[start : start + BENIGN_WINDOW]


def _atr_benign_samples(files: dict[str, bytes]) -> Iterator[tuple[str, str]]:
    for path in sorted(files):
        if not path.startswith(ATR_BENIGN_PREFIXES):
            continue
        body = files[path].decode("utf-8", errors="replace")
        if path.endswith(".jsonl"):
            for line_no, line in enumerate(body.splitlines(), 1):
                record = json.loads(line) if line.strip() else {}
                if isinstance(record.get("text"), str):
                    yield f"atr:{path}:{line_no}", record["text"]
        elif path.endswith(".json"):
            for i, sample in enumerate(json.loads(body).get("samples") or []):
                yield f"atr:{path}#{i}", str(sample.get("text") or "")
        elif path.endswith(".md"):
            yield f"atr:{path}", body


def _local_samples(
    root: Path, globs: Iterable[str], label: str, skip: tuple[str, ...]
) -> Iterator[tuple[str, str]]:
    seen: set[Path] = set()
    for pattern in globs:
        for path in sorted(root.glob(pattern)):
            relative = path.relative_to(root).as_posix()
            if path in seen or any(part in f"/{relative}" for part in skip):
                continue
            seen.add(path)
            text = path.read_text(encoding="utf-8", errors="replace")
            yield f"{label}:{relative}", text


def benign_windows(files: dict[str, bytes]) -> list[tuple[str, str]]:
    paths = sysconfig.get_paths()
    sources = (
        _atr_benign_samples(files),
        _local_samples(Path(paths["stdlib"]), ["**/*.py"], "stdlib", PYTHON_SKIP),
        _local_samples(Path(paths["purelib"]), ["**/*.py"], "deps", PYTHON_SKIP),
        _local_samples(REPO_ROOT, SDK_BENIGN_GLOBS, "sdk", SDK_BENIGN_SKIP),
    )
    return [
        (sample_id, window)
        for source in sources
        for sample_id, text in source
        for window in _windows(text)
    ]


_WORKER_WINDOWS: list[tuple[str, str]] = []


def _load_windows(path: str) -> None:
    with open(path, encoding="utf-8") as handle:
        _WORKER_WINDOWS.extend(tuple(json.loads(line)) for line in handle)


def _first_hit(pattern: str) -> str | None:
    compiled = re.compile(pattern, re.IGNORECASE)
    return next((sid for sid, text in _WORKER_WINDOWS if compiled.search(text)), None)


def benign_hits(
    patterns: dict[str, str], windows: list[tuple[str, str]]
) -> dict[str, str | None]:
    """First benign sample each pattern matches, scanned in worker processes."""
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "windows.jsonl"
        path.write_text("".join(json.dumps(w) + "\n" for w in windows), "utf-8")
        with ProcessPoolExecutor(
            WORKERS, initializer=_load_windows, initargs=(str(path),)
        ) as pool:
            hits = pool.map(_first_hit, patterns.values())
            return dict(zip(patterns, hits))


# ---------------------------------------------------------------------------
# Rule evaluation
# ---------------------------------------------------------------------------


def _matches(pattern: str, text: str) -> bool:
    return re.compile(pattern, re.IGNORECASE).search(_normalize(text)) is not None


def evaluate(rules: list[Rule], windows: list[tuple[str, str]]) -> None:
    """Drop failing conditions in place, then exclude rules that lost a TP."""
    for rule in rules:
        for cond in rule.conditions:
            if cond.dropped is None:
                cond.pattern, cond.dropped = convert(cond.source)
    timings = time_patterns(list(_live(rules).items()))
    for key, share in sorted(timings.items()):
        if share > 0.5:
            print(f"timing {key}: {share:.2f} of budget")
    for rule in rules:
        for cond in (c for c in rule.conditions if c.pattern is not None):
            cond.dropped = _local_failure(rule, cond, timings)
            cond.pattern = None if cond.dropped else cond.pattern
    for key, hit in benign_hits(_live(rules), windows).items():
        if hit is not None:
            _drop(rules, key, f"matches benign text: {hit}")
    for rule in rules:
        live = [c.pattern for c in rule.conditions if c.pattern is not None]
        missed = [
            tp for tp in rule.true_positives if not any(_matches(p, tp) for p in live)
        ]
        if not rule.true_positives:
            rule.excluded.append("no text-field true_positives to verify against")
        if missed:
            rule.excluded.append(
                "surviving conditions miss true_positives: "
                + "; ".join(_clip(tp) for tp in missed)
            )


def _live(rules: list[Rule]) -> dict[str, str]:
    return {
        f"{rule.rule_id}#{cond.index}": cond.pattern
        for rule in rules
        for cond in rule.conditions
        if cond.pattern is not None
    }


def _drop(rules: list[Rule], key: str, reason: str) -> None:
    rule_id, index = key.split("#")
    for rule in (r for r in rules if r.rule_id == rule_id):
        cond = rule.conditions[int(index)]
        cond.pattern, cond.dropped = None, reason


def _local_failure(
    rule: Rule, cond: Condition, timings: dict[str, float]
) -> str | None:
    assert cond.pattern is not None
    if timings.get(f"{rule.rule_id}#{cond.index}", float("inf")) > 1:
        return (
            f"slower than {REDOS_NATIVE_FACTOR}x the slowest built-in pattern on "
            f"adversarial input of {REDOS_INPUT_CHARS} chars"
        )
    hit = next((tn for tn in rule.true_negatives if _matches(cond.pattern, tn)), None)
    return f"matches the rule's own true_negative: {_clip(hit)}" if hit else None


def _clip(text: str, limit: int = 80) -> str:
    flat = " ".join(text.split())
    return flat if len(flat) <= limit else flat[: limit - 3] + "..."


# ---------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------


def _escaped(chunk: str) -> str:
    """A plain string literal; non-printable characters stay visible as escapes."""
    out = []
    for char in chunk:
        if char in '\\"':
            out.append("\\" + char)
        elif char.isprintable():
            out.append(char)
        else:
            code = ord(char)
            out.append(f"\\u{code:04x}" if code <= 0xFFFF else f"\\U{code:08x}")
    return '"' + "".join(out) + '"'


def _literal(chunk: str) -> str:
    if chunk.isprintable() and '"' not in chunk and not chunk.endswith("\\"):
        return f'r"{chunk}"'
    return _escaped(chunk)


def _string_lines(value: str, width: int = 78) -> list[str]:
    """Split ``value`` into implicitly concatenated literals of bounded width.

    A chunk never ends inside a run of backslashes, so it stays a raw literal.
    """
    lines: list[str] = []
    start = 0
    while start < len(value):
        end = start + 1
        while end < len(value) and len(_literal(value[start : end + 1])) <= width:
            end += 1
        while start + 1 < end < len(value) and value[end - 1] == "\\":
            end -= 1
        lines.append(_literal(value[start:end]))
        start = end
    return lines


def _title_lines(title: str, width: int = 78) -> list[str]:
    chunks = textwrap.wrap(title, width - 2, drop_whitespace=False)
    assert "".join(chunks) == title
    return [json.dumps(chunk, ensure_ascii=False) for chunk in chunks]


def _tuple_block(pattern: str, title: str, detector_id: str) -> list[str]:
    pattern_lines = [f"        {line}" for line in _string_lines(pattern)]
    title_lines = [f"        {line}" for line in _title_lines(title)]
    pattern_lines[-1] += ","
    title_lines[-1] += ","
    return [
        "    (",
        *pattern_lines,
        *title_lines,
        f'        "{detector_id}",',
        "    ),",
    ]


def render_module(rules: list[Rule], ref: str, commit: str, license_text: str) -> str:
    blocks: dict[str, list[str]] = {"high": [], "medium": []}
    for rule in rules:
        if rule.excluded:
            continue
        for cond in rule.conditions:
            if cond.pattern is not None:
                blocks[rule.bucket] += _tuple_block(
                    cond.pattern, rule.title, f"atr.{rule.rule_id}"
                )
    return MODULE_TEMPLATE.format(
        ref=ref,
        commit=commit,
        url=ATR_URL,
        license="\n".join(
            ("# " + line).rstrip() for line in license_text.strip().splitlines()
        ),
        high="\n".join(blocks["high"]),
        medium="\n".join(blocks["medium"]),
    )


def render_report(
    rules: list[Rule], out_of_scope: dict[str, str], ref: str, commit: str
) -> dict[str, Any]:
    def dropped(rule: Rule) -> dict[str, str]:
        return {str(c.index): c.dropped for c in rule.conditions if c.dropped}

    return {
        "_comment": (
            "Generated by scripts/generate_atr_patterns.py together with "
            "_atr_pattern_data.py. Do not edit by hand."
        ),
        "source": {
            "repository": ATR_URL,
            "ref": ref,
            "commit": commit,
            "license": "MIT",
        },
        "selection": {
            "lane": "enforce: status not draft/deprecated, maturity stable",
            "categories": list(INJECTION_CATEGORIES),
            "required_tags": [REQUIRED_OWASP_LLM, REQUIRED_OWASP_AGENTIC],
            "fields": list(TEXT_FIELDS),
            "severity_to_bucket": SEVERITY_BUCKET,
        },
        "checks": {
            "python": sys.version.split()[0],
            "redos_budget": (
                f"{REDOS_NATIVE_FACTOR}x the slowest pattern.py default pattern "
                "on its worst adversarial input, re-timed beside every input"
            ),
            "redos_input_chars": REDOS_INPUT_CHARS,
            "benign_corpora": [
                *(f"ATR {ref} {p}" for p in ATR_BENIGN_PREFIXES),
                "Python standard library sources (excluding tests)",
                "Python sources of this repository's locked dependencies "
                "(uv.lock, excluding tests)",
                "this repository: *.md, openhands-sdk and openhands-tools "
                "sources and templates (excluding security/)",
            ],
        },
        "vendored": {
            r.rule_id: {"bucket": r.bucket, "dropped_conditions": dropped(r)}
            for r in rules
            if not r.excluded
        },
        "excluded": {
            r.rule_id: {"reasons": r.excluded, "dropped_conditions": dropped(r)}
            for r in rules
            if r.excluded
        },
        "out_of_scope": out_of_scope,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate the vendored ATR pattern set."
    )
    parser.add_argument("--atr-repo", type=Path, required=True)
    parser.add_argument("--ref", required=True, help="ATR release tag, e.g. v4.1.5")
    args = parser.parse_args()

    commit, files = load_tree(args.atr_repo, args.ref)
    license_text = _mit_license(files)
    rules, out_of_scope = select_rules(files)
    windows = benign_windows(files)
    print(f"{len(rules)} candidate rules, {len(windows)} benign windows")
    evaluate(rules, windows)

    OUT_MODULE.write_text(
        render_module(rules, args.ref, commit, license_text), encoding="utf-8"
    )
    subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--quiet", str(OUT_MODULE)], check=True
    )
    report = render_report(rules, out_of_scope, args.ref, commit)
    OUT_REPORT.parent.mkdir(exist_ok=True)
    OUT_REPORT.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    kept = len(report["vendored"])
    print(f"vendored {kept}, excluded {len(report['excluded'])}; see {OUT_REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
